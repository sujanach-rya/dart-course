//simple operators
void main(List <String> args){
  const age1 = 56;
  const age2 = 34;

  print(age1 + age2); // addition
  print(age1 - age2); // subtraction
  print(age1 * age2); // multiplication
  print(age1 / age2); // division
  print(age1 ~/ age2); // integer division
  print(age1 % age2); // modulus
  print(age1 == age2); // equality
  print(age1 != age2); // inequality
  print(age1 > age2); // greater than
  print(age1 < age2); // less than
  print(age1 >= age2); // greater than or equal to
  print(age1 <= age2); // less than or equal to 

}