void main(List<String> args) {
  const int a = 10;
  print(a);

  const double b = 20.5;
  print(b);

  const String c = "Hello, Dart!";
  print(c);

  const bool d = true;
  print(d);

  const List<int> e = [1, 2, 3, 4, 5];
  print(e);

  const Map<String, String> f = {'name': 'Dart', 'type': 'language'};
  print(f);

  const Set<String> g = {'apple', 'banana', 'cherry'};
  print(g);

  const dynamic h = 'This can be anything';
  print(h);
  
  const Object i = 42;
  print(i);
}