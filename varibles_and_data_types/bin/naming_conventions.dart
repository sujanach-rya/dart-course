void main(List<String> args) {
  
  //camelCase is commonly used for variable names. 
  //It starts with a lowercase letter and each subsequent word starts with an uppercase letter.

  String firstName = 'John';
  String lastName = 'Doe';
  
  // PascalCase
  // Similar to camelCase, but starts with an uppercase letter.
  String FullName = 'John Doe';
  
  // kebab-case
 // Uses hyphens to separate words, often used in URLs or CSS classes.
  
  String fullNameKebab = 'john-doe';

  // snake_case
  // Uses underscores to separate words.
  String full_name = 'John Doe';

  print(full_name);
  print(firstName);
  print(lastName);
  print(fullNameKebab);
  print(FullName);
  
}